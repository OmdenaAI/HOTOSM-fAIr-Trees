import json
from pathlib import Path

import pytest

from experiments.build_results_readme import build, main

ROOT = Path(__file__).resolve().parents[2] / "experiments" / "results"


def _write(d, name, payload):
    (d / name).mkdir(parents=True)
    (d / name / "eval.json").write_text(json.dumps(payload))


def _report(f1, lo, hi):
    return {
        "precision": 0.7,
        "recall": 0.75,
        "f1": f1,
        "f1_ci95": [lo, hi],
        "ap40": 0.6,
        "aoi_f1": 0.71,
        "units": [{}, {}, {}],
    }


def test_build_table(tmp_path):
    _write(tmp_path, "neon-release", _report(0.72, 0.69, 0.75))  # flat format
    _write(
        tmp_path,
        "neon-platform",
        {
            "run_id": "neon-platform",
            "parts": {"val": _report(0.81, 0.78, 0.84), "neon": _report(0.71, 0.68, 0.74)},
        },
    )
    text = build(tmp_path)
    assert text.startswith("# Results") and "Generated by experiments/build_results_readme.py" in text
    lines = [line for line in text.splitlines() if line.startswith("| neon-")]
    assert lines == [
        "| neon-platform | neon | 0.700 | 0.750 | 0.710 [0.680, 0.740] | 0.600 | 0.710 | 3 | – |",
        "| neon-platform | val | 0.700 | 0.750 | 0.810 [0.780, 0.840] | 0.600 | 0.710 | 3 | – |",
        "| neon-release | neon | 0.700 | 0.750 | 0.720 [0.690, 0.750] | 0.600 | 0.710 | 3 | – |",
    ]


def test_part_without_ap40_shows_a_dash(tmp_path):
    merged = _report(0.3, 0.2, 0.4)
    del merged["ap40"]
    _write(tmp_path, "hot-platform", {"run_id": "hot-platform", "parts": {"val_group_merged": merged}})
    [line] = [line for line in build(tmp_path).splitlines() if line.startswith("| hot-")]
    assert line == (
        "| hot-platform | val_group_merged | 0.700 | 0.750 | 0.300 [0.200, 0.400] | – | 0.710 | 3 | – |"
    )


def test_picked_f1_shown_and_reports_without_scores_skipped(tmp_path):
    val = _report(0.5, 0.4, 0.6) | {"f1_picked": 0.569, "picked_threshold": 0.2}
    in_group = {"tree_boxes": 10, "share_in_served_groups": 0.4}
    _write(tmp_path, "hot-groups", {"run_id": "hot-groups", "parts": {"val": val, "val_in_group": in_group}})
    [line] = [line for line in build(tmp_path).splitlines() if line.startswith("| hot-")]
    assert line.endswith("| 3 | 0.569 @0.2 |")


def test_check_mode(tmp_path):
    _write(tmp_path, "neon-release", _report(0.72, 0.69, 0.75))
    assert main(["--results", str(tmp_path), "--check"]) == 1
    assert main(["--results", str(tmp_path)]) == 0
    assert main(["--results", str(tmp_path), "--check"]) == 0


def test_check_mode_accepts_a_crlf_checkout(tmp_path):
    _write(tmp_path, "neon-release", _report(0.72, 0.69, 0.75))
    (tmp_path / "README.md").write_bytes(build(tmp_path).replace("\n", "\r\n").encode("utf-8"))
    assert main(["--results", str(tmp_path), "--check"]) == 0


def test_committed_readme_is_current():
    if not (ROOT / "README.md").exists():
        pytest.skip("no committed results README yet")
    assert (ROOT / "README.md").read_text(encoding="utf-8") == build(ROOT)
