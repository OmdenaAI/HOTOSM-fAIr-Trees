"""Generate the results README from every ``eval.json`` under the results directory.

    python -m experiments.build_results_readme [--results experiments/results] [--check]

Two formats are read: the flat report (top-level ``precision``, ``f1``, ...), treated as the NEON part,
and ``{"run_id", "weights", "parts": {name: report}}``. ``--check`` writes nothing and returns 1 when
the README on disk differs from what would be generated.
"""

import argparse
import json
import logging
from collections.abc import Sequence
from pathlib import Path

logger = logging.getLogger(__name__)

RESULTS = Path(__file__).parent / "results"

HEADER = (
    "# Results\n\n"
    "Generated by experiments/build_results_readme.py from every experiments/results/*/eval.json. "
    "Do not edit by hand.\n\n"
    "F1 is at the 0.1 operating point; F1 @picked at the threshold picked per class on val; IoU 0.5 is "
    "F1 @picked with boxes matched at IoU > 0.5 instead of 0.4.\n\n"
    "| Run | Part | P | R | F1 [95% CI] | AP@0.4 | AOI-F1 | Units | F1 @picked | IoU 0.5 |\n"
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |\n"
)


def collect(results_dir: Path) -> list[dict]:
    """One row per scored (run, part), sorted by ``(run_id, part)``; reports without detection scores
    (``val_in_group``) are left out."""
    rows = []
    for path in sorted(Path(results_dir).glob("*/eval.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        for part, report in (data.get("parts") or {"neon": data}).items():
            if "precision" not in report:
                continue
            rows.append(
                {
                    "run_id": path.parent.name,
                    "part": part,
                    "precision": report["precision"],
                    "recall": report["recall"],
                    "f1": report["f1"],
                    "f1_ci95": report["f1_ci95"],
                    "ap40": report.get("ap40"),  # absent for a part scored at one setting (no sweep)
                    "aoi_f1": report["aoi_f1"],
                    "n_units": len(report["units"]),
                    "f1_picked": report.get("f1_picked"),
                    "picked_threshold": report.get("picked_threshold"),
                    "f1_picked_iou50": report.get("f1_picked_iou50"),  # absent before IoU 0.5 reporting
                }
            )
    return sorted(rows, key=lambda r: (r["run_id"], r["part"]))


def _line(r: dict) -> str:
    lo, hi = r["f1_ci95"]
    ap40 = "–" if r["ap40"] is None else f"{r['ap40']:.3f}"
    picked = "–" if r["f1_picked"] is None else f"{r['f1_picked']:.3f} @{r['picked_threshold']:g}"
    strict = "–" if r["f1_picked_iou50"] is None else f"{r['f1_picked_iou50']:.3f}"
    return (
        f"| {r['run_id']} | {r['part']} | {r['precision']:.3f} | {r['recall']:.3f} | "
        f"{r['f1']:.3f} [{lo:.3f}, {hi:.3f}] | {ap40} | {r['aoi_f1']:.3f} | {r['n_units']} | {picked} | "
        f"{strict} |"
    )


def build(results_dir: Path) -> str:
    return HEADER + "".join(_line(r) + "\n" for r in collect(results_dir))


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--results", type=Path, default=RESULTS)
    parser.add_argument("--check", action="store_true", help="write nothing; return 1 if README.md is stale")
    args = parser.parse_args(argv)
    readme = args.results / "README.md"
    text = build(args.results)
    if args.check:
        # read_text uses universal newlines, so a CRLF checkout (git autocrlf on Windows) is not stale
        current = readme.read_text(encoding="utf-8") if readme.exists() else None
        if current != text:
            logger.error("%s is stale; run python -m experiments.build_results_readme", readme)
            return 1
        return 0
    readme.write_bytes(text.encode("utf-8"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
